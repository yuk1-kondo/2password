//! Password stretching and HKDF key separation (spec §3.2, §4).

use crate::crypto::SymmetricKey;
use crate::{Error, Result};
use argon2::{Algorithm, Argon2, Params, Version};
use hkdf::Hkdf;
use serde::{Deserialize, Serialize};
use sha2::Sha256;

/// Argon2id parameters used to stretch the account password (primary KDF,
/// spec §3.2).
pub const ARGON2_MEMORY_KIB: u32 = 64 * 1024;
pub const ARGON2_ITERATIONS: u32 = 3;
pub const ARGON2_LANES: u32 = 4;

/// PBKDF2-HMAC-SHA256 compatibility mode, matching 1Password's current
/// parameters (spec §3.2).
pub const PBKDF2_ITERATIONS: u32 = 650_000;

/// KDF choice recorded in `profile.json` so accounts can migrate (spec §3).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "algo", rename_all = "snake_case")]
pub enum KdfParams {
    Argon2id { m_kib: u32, t: u32, p: u32 },
    Pbkdf2Sha256 { iterations: u32 },
}

impl Default for KdfParams {
    fn default() -> Self {
        Self::Argon2id {
            m_kib: ARGON2_MEMORY_KIB,
            t: ARGON2_ITERATIONS,
            p: ARGON2_LANES,
        }
    }
}

impl KdfParams {
    /// Stretch `password` with `salt` into a 256-bit key.
    pub fn stretch(&self, password: &[u8], salt: &[u8]) -> Result<SymmetricKey> {
        let mut out = [0u8; 32];
        match self {
            Self::Argon2id { m_kib, t, p } => {
                let params =
                    Params::new(*m_kib, *t, *p, Some(out.len())).map_err(|_| Error::Kdf)?;
                Argon2::new(Algorithm::Argon2id, Version::V0x13, params)
                    .hash_password_into(password, salt, &mut out)
                    .map_err(|_| Error::Kdf)?;
            }
            Self::Pbkdf2Sha256 { iterations } => {
                pbkdf2::pbkdf2_hmac::<Sha256>(password, salt, *iterations, &mut out);
            }
        }
        Ok(SymmetricKey::new(out))
    }
}

/// HKDF-SHA256 with a mandatory domain-separation `info` tag (spec §3).
pub fn hkdf_expand(ikm: &[u8], salt: &[u8], info: &[u8]) -> SymmetricKey {
    let hk = Hkdf::<Sha256>::new(Some(salt), ikm);
    let mut out = [0u8; 32];
    hk.expand(info, &mut out).expect("32 is a valid HKDF length");
    SymmetricKey::new(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use data_encoding::HEXLOWER;

    /// RFC 5869 Test Case 1 (SHA-256, L=32 of the 42-byte OKM).
    #[test]
    fn hkdf_rfc5869_case1() {
        let ikm = [0x0bu8; 22];
        let salt = HEXLOWER.decode(b"000102030405060708090a0b0c").unwrap();
        let info = HEXLOWER.decode(b"f0f1f2f3f4f5f6f7f8f9").unwrap();
        let okm = hkdf_expand(&ikm, &salt, &info);
        assert_eq!(
            HEXLOWER.encode(okm.as_bytes()),
            "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf"
        );
    }

    /// Golden vectors generated by `examples/gen_vectors.rs`; any change to
    /// KDF parameters or domain separation must fail loudly here.
    #[test]
    fn argon2id_golden() {
        let kdf = KdfParams::Argon2id { m_kib: 8 * 1024, t: 1, p: 1 };
        let k = kdf.stretch(b"password", b"0123456789abcdef").unwrap();
        assert_eq!(
            HEXLOWER.encode(k.as_bytes()),
            "fc96682477a0c5c8274a4a7217e2a32b5fd51511377b8ad5be879f728e725aa5"
        );
    }

    #[test]
    fn pbkdf2_golden() {
        let kdf = KdfParams::Pbkdf2Sha256 { iterations: 1000 };
        let k = kdf.stretch(b"password", b"0123456789abcdef").unwrap();
        assert_eq!(
            HEXLOWER.encode(k.as_bytes()),
            "8514638175a45bc45eb1f22f04ff7d27f4f8be480498c455ff4b494ce8d1e7d2"
        );
    }
}
